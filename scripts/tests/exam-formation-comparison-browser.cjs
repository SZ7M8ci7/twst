// Run against Vite dev (TEST_URL). Uses an isolated browser collection/session.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const cards = require('../../src/assets/chara.json');
const mod = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/utils/examPresets.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module: mod, exports: mod.exports });
const preset = mod.exports.examPresetDefinitions.find(p => !p.specialChallenges?.length && p.kind === 'BASIC');
const roster = cards.filter(c => c.rare === 'SSR').slice(0, 5).map(c => ({ name: c.name, level: 80, totsu: 0, magicLevels: [10, 10, 10], buddyLevels: [10, 10, 10], allowUpgrade: true }));
const input = { preset: { ...preset, difficulty: preset.difficulty ?? 1.5 }, roster, supports: [], budget: 0, itemsPerLimitBreak: 1, target: 0, attempts: 30, desiredProbability: .05, tolerance: 0, challengeLocks: {}, maxRemoved: 1, seedTeams: [] };
const candidate = { id: 'comparison-browser', cards: roster.map(c => ({ ...c, originalTotsu: c.totsu, support: false, selectedMagic: [1, 2] })), challengeIds: [], cost: 0, policy: 'effects', estimate: 0 };
const result = { candidate, development: { scores: [], retired: 0, turns: 0 }, validation: { scores: [20000], retired: 0, turns: 4 }, validationTarget: 1 };
const version = fs.readFileSync('src/domain/examSearch/types.ts', 'utf8').match(/ENGINE_VERSION = '([^']+)'/)[1];
const session = { input, version, catalogVersion: 'fixture', checkpoint: { nonce: 'fixture', cursor: 1, seen: [candidate.id], pool: [result], finalists: [result], pending: [], round: 0, elapsed: 10, trialSerial: 1 } };
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    // Local UI checks must not wait for remote fonts or analytics.
    await context.route(/^https:\/\/(fonts\.googleapis\.com|fonts\.gstatic\.com|www\.googletagmanager\.com|www\.google-analytics\.com)\//, route => route.abort());
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(({ input, session, roster }) => {
      if (localStorage.getItem('comparison-fixture')) return;
      localStorage.setItem('comparison-fixture', '1');
      localStorage.setItem('twst-language', 'ja');
      localStorage.setItem('twst-hand-collection', JSON.stringify({ version: 1, data: Object.fromEntries(roster.map(c => [c.name, { cardName: c.name, level: c.level, totsu: c.totsu, isOwned: true }])) }));
      localStorage.setItem('twst-exam-resource-search-v1', JSON.stringify({ ...input, setupVersion: 2 }));
      localStorage.setItem('twst-exam-resource-search-v1-session', JSON.stringify(session));
    }, { input, session, roster });
    await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5175', { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => document.querySelector('#app')?.__vue_app__);
    await page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$router.push('/twst/exam-simulator?tab=search'));
    await page.getByTestId('add-comparison').first().waitFor({ timeout: 30000 });
    fs.mkdirSync('output', { recursive: true });
    await page.locator('.results-table-wrap').first().screenshot({ path: 'output/formation-comparison-selection.png' });
    const handBefore = await page.evaluate(() => localStorage.getItem('twst-hand-collection'));
    await page.getByTestId('add-comparison').first().click();
    const panel = page.getByTestId('formation-comparison');
    assert.equal(await panel.isVisible(), false, 'comparison must be separate from search results');
    await page.getByTestId('comparison-tab').click();
    assert.equal(await page.getByTestId('search-content').isVisible(), true);
    assert.equal(await page.locator('.common-exam-conditions').isVisible(), true);
    assert.equal(await page.locator('.flow-tabs [role="tab"]').count(), 2, 'comparison is not a main flow tab');
    assert.equal(await page.getByTestId('search-results-panel').getByTestId('comparison-tab').count(), 1, 'comparison tab belongs to the results area');
    assert.equal(await page.locator('.results-table-wrap').first().isVisible(), false);
    assert.match(page.url(), /tab=search/);
    assert.equal(await panel.locator('button').first().getAttribute('data-testid'), 'comparison-start', 'compare action is first in the tab');
    assert.equal(await panel.getByTestId('comparison-duplicate').innerText(), '複製');
    await panel.getByTestId('comparison-duplicate').click();
    assert.match(await page.getByTestId('comparison-tab').innerText(), /2/);
    const changed = panel.locator('.entry').nth(1);
    assert.equal(await panel.locator('.card img').count(), 10, 'exactly one icon per card');
    assert.equal(await panel.getByText('レベル上限', { exact: true }).count(), 0);
    await changed.locator('.card select').first().selectOption('3');
    assert.equal(await changed.locator('.card input').first().getAttribute('max'), '115');
    await changed.locator('.card input').first().fill('999');
    await changed.locator('.card input').first().press('Tab');
    assert.equal(await changed.locator('.card input').first().inputValue(), '115');
    await changed.locator('.card select').first().selectOption('0');
    assert.equal(await changed.locator('.card input').first().getAttribute('max'), '100');
    assert.equal(await changed.locator('.card input').first().inputValue(), '100', 'lowering limit breaks clamps the current level');
    await changed.locator('.card select').first().selectOption('3');
    await changed.locator('.card input').first().fill('110');
    await changed.locator('.card input').first().press('Tab');
    assert.equal(await changed.locator('.card input').first().inputValue(), '110');
    assert.equal(await panel.locator('.entry').first().locator('.card input').first().inputValue(), '80');
    assert.equal(await panel.getByTestId('comparison-target').count(), 0);
    assert.equal(await panel.locator('.search-options').count(), 0);
    assert.equal(await panel.locator('.challenge-note').count(), 0);
    const trials = panel.getByRole('spinbutton', { name: '試行回数', exact: true });
    assert.equal(await trials.inputValue(), '10000');
    await trials.press('ArrowUp');
    await trials.press('Tab');
    assert.equal(await trials.inputValue(), '11000');
    await trials.press('ArrowDown');
    await trials.press('Tab');
    assert.equal(await trials.inputValue(), '10000');
    await trials.fill('1000');
    await trials.press('Tab');
    await panel.getByTestId('comparison-start').click();
    assert.equal(await trials.isDisabled(), true);
    assert.equal(await page.getByTestId('resource-start').isDisabled(), true);
    await panel.getByTestId('comparison-start').waitFor({ timeout: 240000 });
    assert.equal(await panel.locator('canvas').count(), 1);
    assert.equal(await panel.locator('.summary-table').count(), 0);
    assert.equal(await panel.locator('.entry-result').count(), 0);
    assert.equal(await panel.getByRole('tab', { name: 'スコア別達成率', exact: true }).getAttribute('aria-selected'), 'true');
    const chartBox = await panel.locator('.chart-row').boundingBox();
    const entriesBox = await panel.locator('.entries').boundingBox();
    assert.ok(chartBox.y + chartBox.height <= entriesBox.y, 'charts precede the teams');
    const scale = panel.getByRole('slider', { name: '対数の強さ' });
    assert.equal(await scale.inputValue(), '0');
    const sliderBox = await scale.boundingBox();
    assert.ok(sliderBox.height > sliderBox.width * 3, 'slider is vertical');
    await scale.press('End');
    await scale.press('Tab');
    assert.equal(await scale.inputValue(), '100');
    await scale.press('Home');
    await scale.press('Tab');
    assert.equal(await page.evaluate(() => localStorage.getItem('twst-hand-collection')), handBefore);
    assert.deepEqual(errors, []);
    fs.mkdirSync('output', { recursive: true });
    await panel.screenshot({ path: 'output/formation-comparison-desktop.png' });
    await page.getByTestId('search-results-panel').screenshot({ path: 'output/formation-comparison-results-tabs.png' });
    await page.screenshot({ path: 'output/formation-comparison-page.png', fullPage: true });
    await panel.getByRole('tab', { name: 'スコア分布', exact: true }).click();
    assert.equal(await panel.getByRole('img', { name: '編成ごとのスコア分布' }).count(), 1);
    await panel.getByRole('tab', { name: 'スコア別達成率', exact: true }).click();
    assert.equal(await panel.getByRole('img', { name: '目標スコアごとの達成率' }).count(), 1);
    await page.setViewportSize({ width: 390, height: 844 });
    await panel.screenshot({ path: 'output/formation-comparison-mobile.png' });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile page must not overflow');
    await changed.locator('.card input').first().fill('100');
    await changed.locator('.card input').first().press('Tab');
    assert.equal(await panel.locator('canvas').count(), 0, 'editing training invalidates the previous chart');
    await panel.getByTestId('comparison-start').click();
    await panel.getByTestId('comparison-stop').click();
    assert.equal(await panel.getByTestId('comparison-start').isEnabled(), true);
    assert.equal(await page.getByTestId('resource-start').isEnabled(), true);
    assert.equal(await page.evaluate(() => localStorage.getItem('twst-hand-collection')), handBefore);
    await page.getByTestId('search-results-tab').click();
    assert.equal(await page.getByTestId('search-content').isVisible(), true);
    assert.equal(await page.getByTestId('add-comparison').first().isChecked(), true);
    await page.getByTestId('add-comparison').first().uncheck();
    await page.getByTestId('comparison-tab').click();
    assert.equal(await panel.locator('.entry').count(), 1, 'deselection removes only the source, leaving the edited copy');
    console.log(JSON.stringify({ passed: true, desktop: 'output/formation-comparison-desktop.png', mobile: 'output/formation-comparison-mobile.png', errors }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
